// Package ee72 provisions an EE72 over the authenticated web-API command
// channel: it removes the adbd lock, sets the console (root) password, and
// makes the debug USB composition the boot default so ADB survives reboots.
//
// Nothing here touches the boot chain, the MTD partitions, or efs2. Every
// mutation is preceded by a backup under /data/jrd/usr/eesetup-<stamp>/.
package ee72

import (
	"fmt"
	"strings"
	"time"
)

// Options controls the on-device procedure.
type Options struct {
	// RootPassword is the new console/SSH password.
	RootPassword string
	// BootComposition is written to /systemrw/boot_hsusb_comp. Default: 0196.
	BootComposition string
	// RemoveLock deletes /jrd-resource/resource/lock_flag so adbd accepts
	// shell/exec/sync services.
	RemoveLock bool
	// Dropbear optionally installs a hard-float dropbear binary and a boot
	// hook. Binary must be an ARMv7 hard-float build for this firmware.
	Dropbear *Dropbear
}

// Dropbear describes an optional SSH server install.
type Dropbear struct {
	Binary []byte
	Port   int
}

// Defaults fills unset fields.
func (o *Options) Defaults() {
	if o.BootComposition == "" {
		o.BootComposition = "0196"
	}
	if o.Dropbear != nil && o.Dropbear.Port == 0 {
		o.Dropbear.Port = 2222
	}
}

// Script builds the on-device shell script. hostIP is the address the device
// uses to fetch optional files.
func Script(o Options, hostIP string) (string, error) {
	o.Defaults()
	stamp := time.Now().Format("20060102-150405")

	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	p("#!/bin/sh")
	p("# Generated by ee-setup. Runs as root via core_app's SetUrlFilterSettings.")
	p("set -e")
	p("H=%s", hostIP)
	p("B=/data/jrd/usr/eesetup-%s", stamp)
	p("PW='%s'", o.RootPassword)
	p("echo '== ee-setup (EE72) =='")
	p("uname -a")
	p("id")
	p("mkdir \"$B\" || { echo 'ERR: backup dir exists'; exit 1; }")

	// 1. Backup.
	p("echo '[1/5] backup ->' \"$B\"")
	p("cp -p /systemrw/boot_hsusb_comp \"$B/boot_hsusb_comp\"")
	p("cp -p /etc/shadow \"$B/shadow\"")
	p("if [ -e /jrd-resource/resource/lock_flag ]; then cp -p /jrd-resource/resource/lock_flag \"$B/lock_flag\"; else : > \"$B/lock_was_absent\"; fi")
	p("sync")

	// Remount helper, documented in docs/ee72_access_method.md.
	p("remount() {")
	p("  printf %%s 'system_u:object_r:sysfs_t:s0' > /proc/self/attr/fscreate")
	p("  printf 'install spidev /bin/mount -n -o remount,%%s /\\n' \"$1\" > /run/ee72_modprobe.conf")
	p("  printf '' > /proc/self/attr/fscreate")
	p("  /sbin/modprobe -C /run/ee72_modprobe.conf spidev")
	p("}")

	p("echo '[2/5] remount / rw'")
	p("if grep -q ' / ubifs rw,' /proc/mounts; then echo 'already rw'; else remount rw; fi")
	p("grep ' / ' /proc/mounts")
	p("grep -q ' / ubifs rw,' /proc/mounts || { echo 'ERR: remount rw failed'; exit 1; }")
	p("RW=1")
	p("trap 'if [ \"$RW\" = 1 ]; then remount ro; fi' EXIT")
	p("trap 'exit 1' HUP INT TERM")

	if o.RemoveLock {
		p("echo '[3/5] adbd lock'")
		p("if [ -e /jrd-resource/resource/lock_flag ]; then rm -f /jrd-resource/resource/lock_flag && echo 'lock removed'; else echo 'lock already absent'; fi")
	}

	p("echo '[4/5] root password'")
	p("if printf '%%s\\n%%s\\n' \"$PW\" \"$PW\" | passwd root >/dev/null 2>&1; then")
	p("  echo 'password set (passwd)'")
	p("else")
	p("  echo 'WARN: could not set the root password; continuing'")
	p("fi")

	if o.Dropbear != nil && len(o.Dropbear.Binary) > 0 {
		p("echo '[5/5] dropbear'")
		p("mkdir -p /data/pre_update")
		p("curl -s \"http://$H/dropbear\" > /data/jrd/usr/dropbear")
		p("chmod 755 /data/jrd/usr/dropbear")
		p("ln -sf dropbear /data/jrd/usr/dropbearkey 2>/dev/null || true")
		p("if [ ! -f /data/jrd/usr/hostkey_rsa ]; then /data/jrd/usr/dropbearkey -t rsa -f /data/jrd/usr/hostkey_rsa; fi")
		p("if [ ! -f /data/jrd/usr/hostkey_ed ]; then /data/jrd/usr/dropbearkey -t ed25519 -f /data/jrd/usr/hostkey_ed; fi")
		p("cat > /data/jrd/usr/ee72-dropbear-boot.sh << 'BOOT'")
		p("#!/bin/sh")
		p("exec /data/jrd/usr/dropbear -p 0.0.0.0:%d -r /data/jrd/usr/hostkey_rsa -r /data/jrd/usr/hostkey_ed -P /tmp/dropbear.pid", o.Dropbear.Port)
		p("BOOT")
		p("cat > /data/pre_update/after_update.sh << 'SHIM'")
		p("#!/bin/sh")
		p("mkdir -p /data/pre_update /data/jrd/usr")
		p("cp /data/jrd/usr/ee72-dropbear-boot.sh /data/pre_update/after_update.sh")
		p("( /bin/sh /data/jrd/usr/ee72-dropbear-boot.sh </dev/null >/dev/null 2>&1 & )")
		p("SHIM")
		p("chmod 755 /data/jrd/usr/ee72-dropbear-boot.sh /data/pre_update/after_update.sh")
		p("( /bin/sh /data/jrd/usr/ee72-dropbear-boot.sh </dev/null >/dev/null 2>&1 & )")
		p("echo 'dropbear on port %d'", o.Dropbear.Port)
	} else {
		p("echo '[5/5] dropbear skipped (no binary supplied)'")
	}

	p("echo '[boot] composition'")
	p("printf %%s %s > /systemrw/boot_hsusb_comp", o.BootComposition)
	p("sync")
	p("printf 'boot_hsusb_comp: '; cat /systemrw/boot_hsusb_comp; echo")

	p("echo DONE")
	return b.String(), nil
}
