func TestPBKDF2Password(t *testing.T) {
	// Vector generated with Python hashlib.pbkdf2_hmac("sha512", ...).
	want := "1a0599a2001a83c708993fc728856d6c76d82c8eaa5eda05007db85a9e554d09" +
		"b9a710e3c4488f19e9dbbaff5d6a9b323507e4fdb5f652a305536bd797e07614"
	if got := PBKDF2Password("test-password", "saltysalt"); got != want {
		t.Fatalf("PBKDF2Password mismatch\n got %s\nwant %s", got, want)
	}
}

func TestFormatStr(t *testing.T) {
	if got := FormatStr("abcdef"); got != "defabc" {
		t.Fatalf("FormatStr = %q, want defabc", got)
	}
}

func TestXOREncrypt(t *testing.T) {
	// Vector generated by the firmware's JS xorEncrypt("admin").
	want := []rune{100, 99, 49, 51, 105, 98, 101, 106, 63, 55}
	got := []rune(XOREncrypt("admin"))
	if len(got) != len(want) {
		t.Fatalf("length %d, want %d", len(got), len(want))
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("rune %d = %d, want %d", i, got[i], want[i])
		}
	}
}

// TestDecryptPythonVector checks interoperability with scripts/ee72_api.py:
// the envelope was produced by pycryptodome with the same EVP_BytesToKey KDF.
func TestDecryptPythonVector(t *testing.T) {
	const envelope = "U2FsdGVkX18AAQIDBAUGB6t7ep7INxxVPKwfUwTLSn6gjZ5d81vhNH6MumKnFPs6"
	var v struct {
		Salt string `json:"Salt"`
	}
	plain, err := Decrypt(envelope, PublicKey)
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(plain, &v); err != nil {
		t.Fatal(err)
	}
	if v.Salt != "AbCd1234Ef" {
		t.Fatalf("salt = %q", v.Salt)
	}
}

func TestRoundTrip(t *testing.T) {
	in := map[string]any{"filter_policy": 2, "UrlDenyList": []string{"'\nsh /tmp/a\n#"}}
	env, err := Encrypt(in, PublicKey)
	if err != nil {
		t.Fatal(err)
	}
	plain, err := Decrypt(env, PublicKey)
	if err != nil {
		t.Fatal(err)
	}
	var out map[string]any
	if err := json.Unmarshal(plain, &out); err != nil {
		t.Fatal(err)
	}
	if out["filter_policy"].(float64) != 2 {
		t.Fatalf("unexpected round trip: %s", plain)
	}
}
